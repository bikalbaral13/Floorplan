const body = (parts) => parts.filter(Boolean).join("\n");
const WORLD_ORIGIN = `_wcx = _cu * _ux + _cv * _vx
_wcy = _cu * _uy + _cv * _vy`;

/** A deterministic 0..1 per row, from a seed. There is no random() in the Math Engine and there
 *  should not be: a layout that changes every time it is evaluated is not a layout. The classic
 *  hash-sine is reproducible, cheap, and good enough for scatter. */
const HASH = (name, k, salt) =>
  `${name} = (sin(${k} * 12.9898 + seed * 78.233 + ${salt}) * 43758.5453) - floor(sin(${k} * 12.9898 + seed * 78.233 + ${salt}) * 43758.5453)`;

