/** STEP 5, part B — the six objects that put life in the room and a world outside the glass.
 *
 *  `bedding` and `cushion` and `decor-cluster` are the clutter a photographed room has and a modelled
 *  one never does. `plant-potted` replaces the faceted green dome with something that has a
 *  silhouette. `exterior-context` and `backplate-plane` are the two answers to the white rectangle
 *  where a window should be — the one defect in the existing renders that no amount of lighting
 *  work can touch, because the problem is that there is nothing out there.
 */
